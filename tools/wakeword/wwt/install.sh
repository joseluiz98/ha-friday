#!/usr/bin/env bash
# Installs the wake-word training code the VM runs on its own (the nightly ambient featcache) from the repo tree this
# script sits in: tools/wakeword/training (no tests) -> $DEST/training, swapped as a whole, plus FRIDAY_VERSION, and
# featcache_nightly.sh -> $DEST. No restart: the units start the script fresh each night. Run as root (scripts/deploy.sh
# and the OTA installer both use sudo / root).
# 18/11/2026 (every satellite):
# - legacy caches amb<YYYYMMDD>.* are the office satellite's: renamed once to amb<YYYYMMDD>_<FRIDAY_SAT_OFFICE>.*
#   (house value from local.env; refused before touching anything if there is a legacy cache and no value);
# - systemd units in $FRIDAY_SYSTEMD_DIR: the service and the 07:00 timer from the repo, and the .path generated with
#   one PathChanged=<incoming>/<sat>/.sync_ok per satellite folder that exists now (a satellite paired later is
#   picked up by the timer until the next install). systemctl runs only with the default systemd dir (tests swap it).
set -euo pipefail
HERE=$(cd "$(dirname "$0")" && pwd)
DEST=${FRIDAY_WWT_DIR:-/opt/friday/wwt}
LINE=${FRIDAY_VERSION_LINE:?FRIDAY_VERSION_LINE missing (use scripts/deploy.sh)}
CACHE=${FRIDAY_WWT_CACHE:-/srv/wwt-featcache}
IN=${FRIDAY_WAKEWORD_INCOMING:-/srv/wakeword-data/incoming}
ENVF=${FRIDAY_LOCAL_CONFIG:-/srv/friday/state/local.env}
UNITS=${FRIDAY_SYSTEMD_DIR:-/etc/systemd/system}
NAME=friday-wwt-featcache

# 1) legacy cache names -> office satellite
legacy=()
for f in "$CACHE"/amb[0-9][0-9][0-9][0-9][0-9][0-9][0-9][0-9].*; do
  [ -e "$f" ] && legacy+=("$f")
done
if [ ${#legacy[@]} -gt 0 ]; then
  OFFICE=${FRIDAY_SAT_OFFICE:-$(sed -n 's/^FRIDAY_SAT_OFFICE=//p' "$ENVF" 2>/dev/null | tail -1 | tr -d "\"' ")}
  [ -n "$OFFICE" ] || { echo "legacy caches in $CACHE but no FRIDAY_SAT_OFFICE in $ENVF" >&2; exit 1; }
  for f in "${legacy[@]}"; do
    b=$(basename "$f"); new="$CACHE/${b:0:11}_$OFFICE.${b:12}"
    if [ -e "$new" ]; then rm -f "$f"; else mv "$f" "$new"; fi
  done
  echo "legacy caches renamed to the office satellite: ${#legacy[@]} files"
fi

# 2) code
mkdir -p "$DEST"
rm -rf "$DEST/.training.new" "$DEST/.training.old"
cp -r "$HERE/../training" "$DEST/.training.new"
find "$DEST/.training.new" \( -name 'test_*' -o -name '__pycache__' \) -prune -exec rm -rf {} +
echo "$LINE" > "$DEST/.training.new/FRIDAY_VERSION"
[ -d "$DEST/training" ] && mv "$DEST/training" "$DEST/.training.old"
mv "$DEST/.training.new" "$DEST/training"
rm -rf "$DEST/.training.old"
cp "$HERE/featcache_nightly.sh" "$DEST/.featcache_nightly.sh.new" && chmod 755 "$DEST/.featcache_nightly.sh.new"
mv -f "$DEST/.featcache_nightly.sh.new" "$DEST/featcache_nightly.sh"

# 3) units
mkdir -p "$UNITS"
for u in service timer; do
  cp "$HERE/$NAME.$u" "$UNITS/.$NAME.$u.new" && chmod 644 "$UNITS/.$NAME.$u.new"
  mv -f "$UNITS/.$NAME.$u.new" "$UNITS/$NAME.$u"
done
paths=""
for d in "$IN"/*/; do
  [ -d "$d" ] && paths+="PathChanged=${d%/}/.sync_ok"$'\n'
done
if [ -n "$paths" ]; then
  printf '[Unit]\nDescription=F.R.I.D.A.Y. wake-word feature cache after a satellite upload (generated by install.sh)\n\n[Path]\n%s\n[Install]\nWantedBy=paths.target\n' \
    "$paths" > "$UNITS/.$NAME.path.new"
  chmod 644 "$UNITS/.$NAME.path.new" && mv -f "$UNITS/.$NAME.path.new" "$UNITS/$NAME.path"
elif [ -e "$UNITS/$NAME.path" ]; then
  # no satellite folder: the timer alone (a .path without paths is invalid)
  [ -z "${FRIDAY_SYSTEMD_DIR:-}" ] && { systemctl disable --now "$NAME.path" || true; }
  rm -f "$UNITS/$NAME.path"
fi
if [ -z "${FRIDAY_SYSTEMD_DIR:-}" ]; then
  systemctl daemon-reload
  systemctl enable "$NAME.timer" ${paths:+"$NAME.path"}
  systemctl restart "$NAME.timer" ${paths:+"$NAME.path"}   # restart: a running .path keeps watching its old list
fi
echo "wake-word training code $LINE installed in $DEST; units in $UNITS ($(printf '%s' "$paths" | grep -c . || true) satellites)"
